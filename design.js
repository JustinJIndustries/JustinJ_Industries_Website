document.addEventListener("DOMContentLoaded", () => {
  const requestedKey = new URLSearchParams(window.location.search).get(
    "design",
  );
  const key = document.body.dataset.designKey || requestedKey;
  const concept = Object.hasOwn(designConcepts, key)
    ? designConcepts[key]
    : null;
  if (!concept) {
    if (requestedKey) {
      document.title = "Design Not Found | JustinJ Industries";
      document.getElementById("design-title").textContent = "Design not found";
      document.querySelector('meta[name="robots"]').content = "noindex, follow";
      document.querySelector('link[rel="canonical"]')?.remove();
    }
    document.getElementById("design-description").innerHTML =
      'Choose a concept from the <a href="/catalogue/">design catalogue</a>.';
    document
      .querySelectorAll(".design-explore, .design-scope")
      .forEach((section) => (section.hidden = true));
    return;
  }

  const title = document.getElementById("design-title");
  const tabs = document.getElementById("design-tabs");
  const panel = document.getElementById("design-panel");
  const loadButton = document.getElementById("preview-load");
  const controls = document.getElementById("preview-controls");
  const desktopButton = document.getElementById("preview-desktop");
  const mobileButton = document.getElementById("preview-mobile");
  const viewportStatus = document.getElementById("preview-viewport-status");
  const mobilePreview = document.getElementById("design-mobile-preview");
  const phoneLayout = window.matchMedia("(max-width: 760px)");
  const previewSlugs = {
    alder: "alder-lane",
    harbor: "harbor-ledger",
    still: "still-form",
    aer: "aer-field",
    northside: "northside",
  };
  const previewSlug = previewSlugs[key];
  // Legacy query links remain usable, including their attribution and fragment.
  // Static project routes provide distinct metadata before JavaScript runs.
  const canonicalUrl = `https://www.justinjindustries.com/design/${previewSlug}/`;
  document.querySelector('link[rel="canonical"]').href = canonicalUrl;
  document.querySelector('meta[property="og:url"]').content = canonicalUrl;
  const mobileImage = document.getElementById("design-mobile-image");
  const mobilePreviewVersion =
    key === "harbor"
      ? "abf6e597d2"
      : key === "northside"
        ? "1f38506f5f"
        : "b5b373813f";
  mobileImage.dataset.src = `/assets/previews/${previewSlug}-mobile.png?v=${mobilePreviewVersion}`;
  mobileImage.dataset.srcset = `${mobileImage.dataset.src} 1x, /assets/previews/${previewSlug}-mobile@3x.webp?v=${mobilePreviewVersion} 3x`;
  mobileImage.alt = `${concept.name} responsive sample homepage preview`;
  mobileImage.width = 390;
  mobileImage.height = 620;
  document.getElementById("design-mobile-link").href =
    `/previews/${previewSlug}/`;
  document
    .getElementById("design-mobile-link")
    .setAttribute("aria-label", `Explore ${concept.name} demo in a new tab`);
  let activeViewport = "desktop";
  let desktopAvailable = false;
  let activePage = 0;
  let previewLoaded = true;

  // The iframe is resized in place, so switching widths retains its page and state.
  function setViewport(mode) {
    if (mode === "desktop" && !desktopAvailable) return;
    activeViewport = mode;
    panel.dataset.viewport = mode;
    desktopButton.setAttribute("aria-pressed", String(mode === "desktop"));
    mobileButton.setAttribute("aria-pressed", String(mode === "mobile"));
    const message =
      mode === "desktop"
        ? "Desktop-width live preview. Use the page tabs to explore the sample."
        : desktopAvailable
          ? "Phone-width live preview. Switch back to Desktop at any time."
          : "Phone-width live preview. Widen this window to enable Desktop.";
    if (viewportStatus.textContent !== message)
      viewportStatus.textContent = message;
  }

  function syncViewportAvailability() {
    const stage = panel.querySelector(".preview-stage");
    if (!stage) return;
    const stageStyle = window.getComputedStyle(stage);
    const usableWidth =
      stage.clientWidth -
      parseFloat(stageStyle.paddingLeft) -
      parseFloat(stageStyle.paddingRight);
    desktopAvailable = usableWidth >= 960;
    desktopButton.disabled = !desktopAvailable;
    desktopButton.title = desktopAvailable
      ? "Preview the live page at desktop width"
      : "Desktop preview needs a wider browser window";
    setViewport(desktopAvailable ? activeViewport : "mobile");
  }

  desktopButton.addEventListener("click", () => setViewport("desktop"));
  mobileButton.addEventListener("click", () => setViewport("mobile"));
  title.textContent = concept.name;
  document.getElementById("sample-pages-title").firstChild.textContent =
    `Explore ${concept.name} pages`;
  document.title = `${key === "northside" ? "Northside" : concept.name} Website Concept | JustinJ Industries`;
  const metadata = document.getElementById("design-type");
  metadata.textContent = concept.type;
  if (concept.startingPrice) {
    const separator = document.createElement("span");
    separator.setAttribute("aria-hidden", "true");
    separator.textContent = " • ";
    const price = document.createElement("span");
    price.className = "design-starting-price";
    price.textContent = `From ${concept.startingPrice}`;
    metadata.append(separator, price);
  }
  document.getElementById("design-description").textContent =
    concept.description;
  document.getElementById("design-scope-copy").textContent =
    concept.calloutIntro;
  document.getElementById("design-scope-details").textContent =
    concept.calloutCopy;
  document.getElementById("design-package-scope").textContent = concept.scope;
  document.getElementById("design-package-terms").textContent = concept.terms;
  document.getElementById("design-package-disclosure").hidden = false;
  document.getElementById("selected-design-name").textContent = concept.name;
  document.getElementById("enquiry-design").value = concept.name;
  document.querySelector(
    `input[name="service_kit"][value="${concept.service}"]`,
  ).checked = true;
  const showPage = (index, focusTab = false) => {
    activePage = index;
    const page = concept.pages[index];
    tabs.querySelectorAll('[role="tab"]').forEach((tab, tabIndex) => {
      const active = tabIndex === index;
      tab.setAttribute("aria-selected", String(active));
      tab.tabIndex = active ? 0 : -1;
      if (active && focusTab) tab.focus();
    });
    panel.className = `design-panel design-panel--${key}`;
    panel.setAttribute("aria-labelledby", `design-tab-${index}`);
    if (!previewLoaded || phoneLayout.matches) return;
    const routeNames = {
      alder: { base: "alder-lane", Projects: "work", About: "about" },
      harbor: { base: "harbor-ledger" },
      still: { base: "still-form", Work: "work" },
      aer: { base: "aer-field", Film: "work", About: "studio" },
      northside: { base: "northside", "Boiler Care": "services/boiler-care" },
    };
    const route = routeNames[key];
    const filename =
      page.name === "Home"
        ? "index"
        : route[page.name] || page.name.toLowerCase();
    const path = `/previews/${route.base}/${filename === "index" ? "" : `${filename}/`}`;
    const frame = document.createElement("iframe");
    frame.className = "sample-iframe";
    frame.title = `${concept.name} ${page.name} sample`;
    frame.src = path;
    frame.setAttribute("sandbox", "allow-scripts");
    frame.setAttribute("allow", "autoplay");
    const openLink = document.createElement("a");
    openLink.className = "sample-open-link";
    openLink.href = path;
    openLink.target = "_blank";
    openLink.rel = "noopener";
    openLink.textContent = `Open full ${page.name} sample page`;
    const stage = document.createElement("div");
    stage.className = "preview-stage";
    stage.append(frame);
    panel.replaceChildren(stage, openLink);
    syncViewportAvailability();
  };

  concept.pages.forEach((page, index) => {
    const button = document.createElement("button");
    button.type = "button";
    button.id = `design-tab-${index}`;
    button.setAttribute("role", "tab");
    button.setAttribute("aria-controls", "design-panel");
    button.textContent = page.name;
    button.addEventListener("click", () => showPage(index));
    button.addEventListener("keydown", (event) => {
      const keys = ["ArrowRight", "ArrowLeft", "Home", "End"];
      if (!keys.includes(event.key)) return;
      event.preventDefault();
      const next =
        event.key === "Home"
          ? 0
          : event.key === "End"
            ? concept.pages.length - 1
            : (index +
                (event.key === "ArrowRight" ? 1 : -1) +
                concept.pages.length) %
              concept.pages.length;
      showPage(next, true);
    });
    tabs.append(button);
  });
  const showUnloadedState = () => {
    panel.removeAttribute("data-viewport");
    panel.replaceChildren();
    panel.hidden = true;
    controls.hidden = true;
    viewportStatus.hidden = true;
  };
  const syncPresentation = () => {
    const phone = phoneLayout.matches;
    if (phone && mobileImage.getAttribute("src") !== mobileImage.dataset.src) {
      mobileImage.srcset = mobileImage.dataset.srcset;
      mobileImage.src = mobileImage.dataset.src;
    }
    mobilePreview.hidden = !phone;
    loadButton.hidden = phone;
    if (phone) {
      // Remove video and scripts from the live sample when only its image is shown.
      showUnloadedState();
    } else if (previewLoaded) {
      panel.hidden = false;
      controls.hidden = false;
      viewportStatus.hidden = false;
      showPage(activePage);
      setViewport(activeViewport);
    }
  };
  phoneLayout.addEventListener("change", syncPresentation);
  loadButton.addEventListener("click", () => {
    previewLoaded = !previewLoaded;
    loadButton.setAttribute("aria-expanded", String(previewLoaded));
    loadButton.textContent = previewLoaded
      ? "Hide Interactive Preview"
      : "Load Interactive Preview";
    if (previewLoaded) {
      panel.hidden = false;
      controls.hidden = false;
      viewportStatus.hidden = false;
      showPage(activePage);
      setViewport(activeViewport);
    } else {
      // Remove the iframe so hidden videos, audio, and scripts stop running.
      showUnloadedState();
    }
  });
  syncPresentation();
  if (typeof ResizeObserver === "function") {
    new ResizeObserver(syncViewportAvailability).observe(panel);
  } else {
    window.addEventListener("resize", syncViewportAvailability);
  }

  const dialog = document.getElementById("enquiry-dialog");
  const form = document.getElementById("enquiry-form");
  const steps = [...form.querySelectorAll(".enquiry-step")];
  const back = document.getElementById("enquiry-back");
  const next = document.getElementById("enquiry-next");
  const submit = document.getElementById("enquiry-submit");
  const error = document.getElementById("enquiry-error");
  const dateWrap = document.getElementById("desired-date-wrap");
  const dateInput = document.getElementById("desired-date");
  const review = document.getElementById("enquiry-review");
  const applyPageDefaults = () => {
    form.elements.page_faq.checked = key === "harbor";
    form.elements.page_projects.checked = key === "still" || key === "aer";
  };
  applyPageDefaults();
  let currentStep = 0;
  let dirty = false;
  let sending = false;
  let sent = false;
  let opener;

  const showError = (message, control) => {
    error.textContent = message;
    error.hidden = false;
    if (control) {
      control.setAttribute("aria-invalid", "true");
      const descriptions = new Set(
        (control.getAttribute("aria-describedby") || "")
          .split(/\s+/)
          .filter(Boolean),
      );
      descriptions.add("enquiry-error");
      control.setAttribute("aria-describedby", [...descriptions].join(" "));
      control.focus();
    } else error.focus();
  };
  const clearError = () => {
    error.textContent = "";
    error.hidden = true;
    form.querySelectorAll('[aria-invalid="true"]').forEach((control) => {
      control.removeAttribute("aria-invalid");
      const descriptions = (control.getAttribute("aria-describedby") || "")
        .split(/\s+/)
        .filter((id) => id && id !== "enquiry-error");
      if (descriptions.length)
        control.setAttribute("aria-describedby", descriptions.join(" "));
      else control.removeAttribute("aria-describedby");
    });
  };
  const showStep = (index) => {
    currentStep = index;
    steps.forEach((step, number) => {
      step.hidden = number !== index;
    });
    back.hidden = index === 0;
    next.hidden = index === steps.length - 1;
    submit.hidden = index !== steps.length - 1;
    document.getElementById("enquiry-progress").textContent =
      `Step ${index + 1} of 4: ${["Project", "Content and setup", "Timing and contact", "Review"][index]}`;
    document.getElementById("enquiry-progress-fill").style.transform =
      `scaleX(${(index + 1) / steps.length})`;
    clearError();
    const heading = steps[index].querySelector("h3");
    heading.tabIndex = -1;
    heading.focus();
  };
  const firstInvalid = () =>
    [...steps[currentStep].querySelectorAll("input, select, textarea")].find(
      (control) => !control.checkValidity(),
    );
  const validateStep = () => {
    const invalid = firstInvalid();
    if (invalid) {
      showError("Please complete this field before continuing.", invalid);
      return false;
    }
    if (
      currentStep === 0 &&
      !form.querySelector('input[name^="page_"]:checked')
    ) {
      showError(
        "Choose at least one page.",
        form.querySelector('input[name^="page_"]'),
      );
      return false;
    }
    if (currentStep === 2) {
      if (
        form.querySelector('input[name="timing"]:checked')?.value ===
          "Desired date" &&
        !dateInput.value
      ) {
        showError("Enter your desired date.", dateInput);
        return false;
      }
      const email = form.elements.email;
      const phone = form.elements.phone;
      if (!email.value.trim() && !phone.value.trim()) {
        showError(
          "Provide an email address or phone number so we can respond.",
          email,
        );
        return false;
      }
    }
    return true;
  };
  const addReview = (label, value) => {
    const dt = document.createElement("dt");
    const dd = document.createElement("dd");
    dt.textContent = label;
    dd.textContent = value || "Not provided";
    review.append(dt, dd);
  };
  const populateReview = () => {
    review.replaceChildren();
    const values = new FormData(form);
    addReview("Design", concept.name);
    addReview("Starting service", values.get("service_kit"));
    addReview(
      "Pages",
      [...form.querySelectorAll('input[name^="page_"]:checked')]
        .map((field) => field.value)
        .join(", "),
    );
    addReview("Site goal", values.get("goals"));
    addReview("Copy and images", values.get("content_readiness"));
    addReview(
      "Hosting / domain",
      `${values.get("hosting_readiness")} / ${values.get("domain_readiness")}`,
    );
    addReview(
      "Features",
      values.getAll("features").join(", ") || "None selected",
    );
    addReview("Feature notes", values.get("feature_notes"));
    addReview(
      "Timing",
      values.get("timing") === "Desired date"
        ? `Desired date: ${values.get("desired_date")}`
        : values.get("timing"),
    );
    addReview(
      "Contact",
      [
        values.get("first_name"),
        values.get("last_name"),
        values.get("business_name"),
        values.get("email"),
        values.get("phone"),
      ]
        .filter(Boolean)
        .join(" · "),
    );
  };
  const resetJourney = () => {
    form.reset();
    applyPageDefaults();
    form.querySelector(
      `input[name="service_kit"][value="${concept.service}"]`,
    ).checked = true;
    form.elements.design.value = concept.name;
    form.elements.form_loaded_at.value = new Date().toISOString();
    dateWrap.hidden = true;
    dateInput.required = false;
    dirty = false;
    sent = false;
    form.hidden = false;
    dialog.querySelector(".enquiry-success")?.remove();
    showStep(0);
  };
  const requestClose = () => {
    if (sending) return;
    if (
      dirty &&
      !sent &&
      !window.confirm("Discard this inquiry? Your answers will be lost.")
    )
      return;
    dialog.close();
  };

  document
    .querySelectorAll("#enquiry-open, #enquiry-open-bottom")
    .forEach((button) => {
      button.hidden = false;
      button.addEventListener("click", () => {
        opener = button;
        form.elements.form_loaded_at.value = new Date().toISOString();
        dialog.showModal();
        showStep(currentStep);
      });
    });
  document
    .getElementById("enquiry-close")
    .addEventListener("click", requestClose);
  dialog.addEventListener("cancel", (event) => {
    event.preventDefault();
    requestClose();
  });
  dialog.addEventListener("click", (event) => {
    if (event.target === dialog) requestClose();
  });
  dialog.addEventListener("close", () => {
    opener?.focus();
    resetJourney();
  });
  form.addEventListener("input", () => {
    dirty = true;
    clearError();
  });
  form.addEventListener("change", (event) => {
    dirty = true;
    clearError();
    if (event.target.name === "timing") {
      const hasDate = event.target.value === "Desired date";
      dateWrap.hidden = !hasDate;
      dateInput.required = hasDate;
      if (!hasDate) dateInput.value = "";
    }
  });
  next.addEventListener("click", () => {
    if (!validateStep()) return;
    if (currentStep === 2) populateReview();
    showStep(currentStep + 1);
  });
  back.addEventListener("click", () => showStep(currentStep - 1));
  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    if (sending || sent) return;
    if (!validateStep()) return;
    sending = true;
    submit.disabled = true;
    submit.textContent = "Sending…";
    clearError();
    try {
      const response = await fetch(form.action, {
        method: "POST",
        body: new FormData(form),
        headers: { Accept: "application/json" },
      });
      const result = await response.json();
      if (!response.ok || result.ok !== true)
        throw new Error("Submission was not accepted.");
      sent = true;
      dirty = false;
      form.hidden = true;
      const message = document.createElement("p");
      message.className = "enquiry-success";
      message.tabIndex = -1;
      message.setAttribute("role", "status");
      message.textContent =
        "Your inquiry was submitted. JustinJ Industries will review it and follow up with next steps.";
      dialog.querySelector(".enquiry-shell").append(message);
      message.focus();
    } catch {
      showError(
        "Your inquiry could not be sent. Your answers are still here. Please retry or email info@justinjindustries.com.",
      );
    } finally {
      sending = false;
      submit.disabled = false;
      submit.textContent = "Send inquiry";
    }
  });
});
